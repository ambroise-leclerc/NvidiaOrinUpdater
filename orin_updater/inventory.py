"""Inventory of installed software, and a *reviewable* reinstall script for the new system.

Nothing here is installed automatically: Ubuntu 22.04 -> 24.04 renames/drops packages and
JetPack 7 ships its own CUDA/TensorRT stack, so the user reviews and runs reinstall.sh.
"""

from __future__ import annotations

import re
import shutil
import subprocess
from pathlib import Path

# Packages provided (in a new version) by JetPack 7 itself, or tied to Ubuntu 22.04.
SKIP_PATTERNS = [
    r"^nvidia-l4t-.*", r"^nvidia-jetpack.*", r"^nvidia-container.*", r"^cuda.*",
    r"^libcudnn.*", r"^libnvinfer.*", r"^libnvonnxparsers.*", r"^libnvparsers.*",
    r"^tensorrt.*", r"^python3-libnvinfer.*", r"^nvidia-.*", r"^libnvidia-.*",
    r"^vpi\d.*", r"^libnvvpi.*", r"^deepstream.*", r"^nsight.*", r"^l4t-.*",
    r"^python3\.10.*", r"^libpython3\.10.*", r"^linux-.*", r"^ubuntu-.*",
]
_SKIP_RE = re.compile("|".join(SKIP_PATTERNS))


def _run(cmd: list[str], user: str | None = None) -> str | None:
    if shutil.which(cmd[0]) is None:
        return None
    if user is not None and shutil.which("sudo"):
        cmd = ["sudo", "-u", user, "-H", "--", *cmd]
    try:
        res = subprocess.run(cmd, capture_output=True, text=True, timeout=120)
    except (OSError, subprocess.SubprocessError):
        return None
    return res.stdout if res.returncode == 0 else None


def collect(dest: Path, user: str) -> dict[str, str]:
    """Write inventory files into `dest`; return {name: content}."""
    dest.mkdir(parents=True, exist_ok=True)
    items = {
        "apt-manual.txt": _run(["apt-mark", "showmanual"]),
        "apt-sources.txt": _apt_sources(),
        "snap-list.txt": _run(["snap", "list"]),
        "docker-images.txt": _run(
            ["docker", "images", "--format", "{{.Repository}}:{{.Tag}}"]),
        "pip-user.txt": _run(["python3", "-m", "pip", "list", "--user", "--format=freeze"], user),
        "cargo-install.txt": _run(["cargo", "install", "--list"], user),
        "user-crontab.txt": _run(["crontab", "-l"], user),
    }
    written = {}
    for name, content in items.items():
        if content:
            (dest / name).write_text(content)
            written[name] = content
    (dest / "reinstall.sh").write_text(render_reinstall(written))
    (dest / "reinstall.sh").chmod(0o755)
    return written


def _apt_sources() -> str:
    lines = []
    for f in sorted(Path("/etc/apt/sources.list.d").glob("*")):
        if f.suffix in (".list", ".sources"):
            lines.append(f"# {f.name}")
            lines += [ln for ln in f.read_text(errors="replace").splitlines()
                      if ln.strip() and not ln.lstrip().startswith("#")]
    return "\n".join(lines) + "\n" if lines else ""


def parse_snap_list(text: str) -> list[tuple[str, str]]:
    """Return [(name, channel)] from `snap list` output, skipping base/system snaps."""
    out = []
    for line in text.splitlines()[1:]:
        cols = line.split()
        if len(cols) < 4:
            continue
        name, tracking = cols[0], cols[3]
        notes = cols[5] if len(cols) > 5 else ""
        if notes in ("base", "core", "snapd") or name in ("snapd", "bare") or name.startswith(
                ("core", "gnome-", "gtk-common-themes", "mesa-")):
            continue
        out.append((name, tracking))
    return out


def render_reinstall(inv: dict[str, str]) -> str:
    out = [
        "#!/bin/sh",
        "# Generated by orin-updater. REVIEW BEFORE RUNNING.",
        "# Source system: Ubuntu 22.04 / JetPack 6. Target: Ubuntu 24.04 / JetPack 7.",
        "# Lines are commented out on purpose: uncomment what you want.",
        "set -e",
        "",
        "# JetPack components (CUDA, TensorRT, cuDNN, VPI...):",
        "# sudo apt update && sudo apt install -y nvidia-jetpack",
        "",
    ]
    apt = [p.split(":")[0] for p in (inv.get("apt-manual.txt") or "").split()]
    keep = sorted(p for p in apt if not _SKIP_RE.match(p))
    skipped = sorted(p for p in apt if _SKIP_RE.match(p))
    if keep:
        out.append("# --- apt packages you installed manually ---")
        out += [f"# sudo apt install -y {p}" for p in keep]
        out.append("")
    if skipped:
        out.append("# Skipped (provided by JetPack 7 / Ubuntu 24.04 or version-specific): "
                   + " ".join(skipped))
        out.append("")
    if inv.get("apt-sources.txt"):
        out.append("# --- third-party apt repositories (check they publish 'noble' / 24.04) ---")
        out += [f"#   {ln}" for ln in inv["apt-sources.txt"].splitlines()]
        out.append("")
    snaps = parse_snap_list(inv.get("snap-list.txt") or "")
    if snaps:
        out.append("# --- snaps ---")
        for name, chan in snaps:
            classic = " --classic" if _is_classic(inv["snap-list.txt"], name) else ""
            out.append(f"# sudo snap install {name} --channel={chan}{classic}")
        out.append("")
    if inv.get("docker-images.txt"):
        out.append("# --- docker images (pull again; L4T-based images must match R39) ---")
        out += [f"# docker pull {img}" for img in inv["docker-images.txt"].split()
                if not img.endswith(":<none>")]
        out.append("")
    if inv.get("pip-user.txt"):
        out.append("# --- pip --user packages (Python 3.12 on 24.04: prefer venvs / pipx) ---")
        out += [f"# pip install --user {ln}" for ln in inv["pip-user.txt"].split()]
        out.append("")
    if inv.get("cargo-install.txt"):
        out.append("# --- cargo install ---")
        out += [f"# cargo install {ln.split()[0]}" for ln in inv["cargo-install.txt"].splitlines()
                if ln and not ln.startswith(" ")]
        out.append("")
    return "\n".join(out) + "\n"


def _is_classic(snap_text: str, name: str) -> bool:
    for line in snap_text.splitlines():
        cols = line.split()
        if cols and cols[0] == name:
            return len(cols) > 5 and "classic" in cols[5].split(",")
    return False
